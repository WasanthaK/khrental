import crypto from 'node:crypto';
import { normalizeInvoiceDocumentSnapshot } from './invoicePdfCandidate.js';

// Draft-only archive boundary. This module deliberately cannot write objects,
// send emails, issue invoices, or authorize HTTP requests. A future guarded
// archive ledger must bind these descriptors to one committed issued invoice.
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
const HASH = /^[0-9a-f]{64}$/;
const MAX_PDF_BYTES = 5 * 1024 * 1024;

const reject = (message, code = 'INVOICE_ARCHIVE_INVALID') => {
  const error = new Error(message);
  error.code = code;
  throw error;
};
const id = (value, label) => {
  if (typeof value !== 'string' || !UUID.test(value)) reject('Invalid ' + label);
  return value.toLowerCase();
};
const hash = (value, label) => {
  if (typeof value !== 'string' || !HASH.test(value)) reject('Invalid ' + label);
  return value;
};
const sha256 = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const normalizeBytes = value => {
  if (!Buffer.isBuffer(value) && !(value instanceof Uint8Array)) {
    reject('Archive contents must be verified PDF bytes.');
  }
  const bytes = Buffer.from(value);
  if (bytes.length < 100 || bytes.length > MAX_PDF_BYTES ||
      bytes.subarray(0, 5).toString('ascii') !== '%PDF-') {
    reject('Archive has invalid PDF contents or size.');
  }
  return bytes;
};

export const issuedInvoiceArchivePath = ({ tenantId, invoiceId, pdfSha256 }) =>
  'tenants/' + id(tenantId, 'tenant ID') + '/invoices/' +
  id(invoiceId, 'invoice ID') + '/issued/sha256-' +
  hash(pdfSha256, 'PDF SHA-256') + '.pdf';

const normalizedSnapshotHash = source =>
  sha256(Buffer.from(JSON.stringify(normalizeInvoiceDocumentSnapshot(source))));

// Construct a candidate from generated bytes. Never upload from this helper;
// persistence must use a transactional, fenced, write-once archive contract.
export const prepareInvoiceArchiveCandidate = ({ snapshot, pdfBytes }) => {
  const normalized = normalizeInvoiceDocumentSnapshot(snapshot);
  const bytes = normalizeBytes(pdfBytes);
  const pdfSha256 = sha256(bytes);
  const snapshotSha256 = normalizedSnapshotHash(normalized);
  const tenantId = id(normalized.tenantId, 'tenant ID');
  const invoiceId = id(normalized.invoiceId, 'invoice ID');
  return Object.freeze({
    tenantId, invoiceId, bucket: 'invoices',
    path: issuedInvoiceArchivePath({ tenantId, invoiceId, pdfSha256 }),
    pdfSha256, snapshotSha256,
    byteLength: bytes.length,
    version: 1
  });
};

// Load only a trusted committed archive manifest. Wrong scope, missing bytes,
// hash mismatch, deletion, corruption and metadata drift all fail closed.
// No render fallback is permitted: resend must use these returned exact bytes.
export const readRetainedInvoiceArchiveCandidate = async ({
  archive, tenantId, invoiceId, getObject
}) => {
  if (!archive || typeof archive !== 'object' || Array.isArray(archive) ||
      typeof getObject !== 'function') reject('Archive manifest and reader required.');
  const targetTenantId = id(tenantId, 'request tenant ID');
  const targetInvoiceId = id(invoiceId, 'request invoice ID');
  const archivedTenantId = id(archive.tenantId, 'archive tenant ID');
  const archivedInvoiceId = id(archive.invoiceId, 'archive invoice ID');
  if (targetTenantId !== archivedTenantId || targetInvoiceId !== archivedInvoiceId) {
    reject('Invoice archive does not belong to the requested tenant and invoice.',
      'INVOICE_ARCHIVE_SCOPE_DENIED');
  }
  const pdfSha256 = hash(archive.pdfSha256, 'PDF SHA-256');
  hash(archive.snapshotSha256, 'snapshot SHA-256');
  if (archive.version !== 1 || archive.bucket !== 'invoices' ||
      archive.state !== 'committed' ||
      !Number.isInteger(archive.byteLength) || archive.byteLength < 100 ||
      archive.byteLength > MAX_PDF_BYTES) reject('Invoice archive is not committed and valid.');
  const canonicalPath = issuedInvoiceArchivePath({
    tenantId: archivedTenantId, invoiceId: archivedInvoiceId, pdfSha256
  });
  if (archive.path !== canonicalPath) reject('Invoice archive path is not canonical.');

  // Caller is responsible for authorization to read this invoice and fetching
  // its authoritative ledger row; this is a second fail-closed data boundary.
  const result = await getObject('invoices', canonicalPath);
  const bytes = normalizeBytes(result?.body);
  if (bytes.length !== archive.byteLength || sha256(bytes) !== pdfSha256) {
    reject('Retained invoice PDF bytes differ from the committed archive manifest.',
      'INVOICE_ARCHIVE_INTEGRITY_FAILED');
  }
  return bytes;
};
